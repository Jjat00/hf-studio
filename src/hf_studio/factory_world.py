def is_land(lon: float, lat: float) -> bool:
    """Punto dentro de algún contorno (rayo horizontal)."""
    for poly in LAND:
        inside = False
        j = len(poly) - 1
        for i, (xi, yi) in enumerate(poly):
            xj, yj = poly[j]
            if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                inside = not inside
            j = i
        if inside:
            return True
    return False
